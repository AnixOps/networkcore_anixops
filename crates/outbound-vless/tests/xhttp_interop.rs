//! Interop tests of VLESS over XHTTP against real Xray-core servers.
//!
//! These tests are ignored by default; the `REALITY interop (Linux)` CI job
//! starts the servers and targets and runs them with `--ignored`. Inputs:
//!
//! * `NC_XHTTP_PLAIN`: Xray VLESS + XHTTP without TLS, path `/xh`
//! * `NC_XHTTP_TLS`: the same with TLS (ALPN `h2` and `http/1.1`) and the
//!   certificate for `NC_SERVER_NAME`
//! * `NC_XHTTP_REALITY`: the same over REALITY (`NC_REALITY_SERVER_NAME`,
//!   `NC_REALITY_PUBLIC_KEY`, `NC_REALITY_SHORT_ID`)
//! * `NC_VLESS_UUID`
//! * `NC_HTTP_TARGET`: plain HTTP/1.0 server serving `/payload.bin`
//!   generated by [`expected_payload`]
//! * `NC_TCP_ECHO`: TCP echo server

use std::io;
use std::net::SocketAddr;
use std::sync::Arc;
use std::time::Duration;

use engine_outbound::registry::OutboundRegistry;
use engine_outbound::{TargetAddr, TcpDialer, TcpOutbound};
use outbound_vless::VlessFactory;
use serde_json::{json, Value};
use tokio::io::{AsyncReadExt, AsyncWriteExt};

const PAYLOAD_LEN: usize = 1_000_000;
const ECHO_LEN: usize = 300_000;
const TIMEOUT: Duration = Duration::from_secs(60);

fn expected_payload() -> Vec<u8> {
    (0..PAYLOAD_LEN)
        .map(|i| ((i * 7 + 3) % 251) as u8)
        .collect()
}

fn env(name: &str) -> String {
    std::env::var(name).unwrap_or_else(|_| panic!("{name} must be set for interop tests"))
}

/// The security layer of a case.
#[derive(Clone, Copy)]
enum Layer {
    Plain,
    /// Standard TLS with this ALPN.
    Tls(&'static [&'static str]),
    Reality,
}

use Layer::{Plain, Reality, Tls};

/// (label, server env, layer, mode)
const CASES: &[(&str, &str, Layer, &str)] = &[
    ("plain http/1.1 packet-up", "NC_XHTTP_PLAIN", Plain, "auto"),
    (
        "tls http/1.1 packet-up",
        "NC_XHTTP_TLS",
        Tls(&["http/1.1"]),
        "packet-up",
    ),
    ("tls h2 packet-up", "NC_XHTTP_TLS", Tls(&[]), "packet-up"),
    ("tls h2 stream-up", "NC_XHTTP_TLS", Tls(&[]), "stream-up"),
    ("tls h2 stream-one", "NC_XHTTP_TLS", Tls(&[]), "stream-one"),
    ("reality stream-one", "NC_XHTTP_REALITY", Reality, "auto"),
    (
        "reality stream-up",
        "NC_XHTTP_REALITY",
        Reality,
        "stream-up",
    ),
    (
        "reality packet-up",
        "NC_XHTTP_REALITY",
        Reality,
        "packet-up",
    ),
];

fn outbound(server: &str, layer: Layer, mode: &str) -> Arc<dyn TcpOutbound> {
    let address: SocketAddr = server.parse().unwrap();
    let mut settings = json!({
        "server": address.ip().to_string(),
        "port": address.port(),
        "uuid": env("NC_VLESS_UUID"),
        "transport": {"type": "xhttp", "path": "/xh", "mode": mode},
    });
    match layer {
        Plain => {}
        Tls(alpn) => {
            settings["tls"] = json!({
                "server_name": env("NC_SERVER_NAME"),
                "alpn": alpn,
                "insecure": true,
            });
        }
        Reality => {
            settings["reality"] = json!({
                "server_name": env("NC_REALITY_SERVER_NAME"),
                "public_key": env("NC_REALITY_PUBLIC_KEY"),
                "short_id": env("NC_REALITY_SHORT_ID"),
            });
        }
    }
    let Value::Object(settings) = settings else {
        unreachable!()
    };
    let mut registry = OutboundRegistry::new();
    registry.register(Arc::new(VlessFactory));
    registry
        .build("vless", &settings, Arc::new(TcpDialer))
        .unwrap_or_else(|error| panic!("{server} {mode}: {error}"))
}

async fn fetch_payload(outbound: &dyn TcpOutbound) -> io::Result<Vec<u8>> {
    let target = TargetAddr::from(env("NC_HTTP_TARGET").parse::<SocketAddr>().unwrap());
    let mut stream = outbound.connect(&target).await?;
    stream
        .write_all(b"GET /payload.bin HTTP/1.0\r\nHost: interop.test\r\n\r\n")
        .await?;
    stream.flush().await?;
    let mut response = Vec::new();
    stream.read_to_end(&mut response).await?;
    let split = response
        .windows(4)
        .position(|window| window == b"\r\n\r\n")
        .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, "no HTTP header terminator"))?;
    let status = String::from_utf8_lossy(&response[..split]).to_string();
    if !(status.starts_with("HTTP/1.0 200") || status.starts_with("HTTP/1.1 200")) {
        return Err(io::Error::other(format!("unexpected status: {status}")));
    }
    Ok(response[split + 4..].to_vec())
}

/// Sends `ECHO_LEN` bytes in uneven writes while reading them back, which
/// takes many uploads in `packet-up`.
async fn echo(outbound: &dyn TcpOutbound) -> io::Result<()> {
    let target = TargetAddr::from(env("NC_TCP_ECHO").parse::<SocketAddr>().unwrap());
    let stream = outbound.connect(&target).await?;
    let (mut reader, mut writer) = tokio::io::split(stream);
    let sent: Vec<u8> = (0..ECHO_LEN).map(|i| (i % 253) as u8).collect();
    let expected = sent.clone();
    let writing = tokio::spawn(async move {
        for (index, piece) in sent.chunks(7_919).enumerate() {
            writer.write_all(piece).await?;
            writer.flush().await?;
            if index % 8 == 0 {
                tokio::time::sleep(Duration::from_millis(5)).await;
            }
        }
        io::Result::Ok(writer)
    });
    let mut received = vec![0u8; ECHO_LEN];
    reader.read_exact(&mut received).await?;
    let _writer = writing.await.map_err(io::Error::other)??;
    if received != expected {
        return Err(io::Error::other("echoed bytes differ"));
    }
    Ok(())
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
#[ignore = "needs the REALITY interop CI environment"]
async fn relays_through_xray_xhttp_in_every_mode() {
    let expected = expected_payload();
    let mut failures = Vec::new();
    for (label, server, layer, mode) in CASES {
        let outbound = outbound(&env(server), *layer, mode);
        match tokio::time::timeout(TIMEOUT, fetch_payload(outbound.as_ref())).await {
            Ok(Ok(body)) if body == expected => eprintln!("{label}: download ok"),
            Ok(Ok(body)) => failures.push(format!("{label}: {} bytes differ", body.len())),
            Ok(Err(error)) => failures.push(format!("{label} download: {error}")),
            Err(_) => failures.push(format!("{label} download: timed out")),
        }
        match tokio::time::timeout(TIMEOUT, echo(outbound.as_ref())).await {
            Ok(Ok(())) => eprintln!("{label}: echo ok"),
            Ok(Err(error)) => failures.push(format!("{label} echo: {error}")),
            Err(_) => failures.push(format!("{label} echo: timed out")),
        }
    }
    assert!(failures.is_empty(), "failures:\n{}", failures.join("\n"));
}
